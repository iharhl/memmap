"""Write a partition import as config text: a region and column per flash device or memory
region, one line per partition, and a detail column for each partition that holds others."""

from __future__ import annotations

from ..from_elf.blocks import Bucket, Item
from ..from_elf.sizes import address_literal, size_literal
from ..from_elf.writer import COLUMN_WIDTH, comment_safe, item_lines, quote, usage_title
from .areas import Region
from .esp_idf import SECTOR

BITS = 32  # addresses are drawn with 32 bits, unless one needs more


def _expansions(items: list[Item], within: str) -> list[tuple[Item, str]]:
    """Each block that holds others, depth first, with the name of what holds it."""
    found: list[tuple[Item, str]] = []
    for item in items:
        if item.expanded:
            found.append((item, within))
            found += _expansions(item.children, item.name.replace("\n", " "))
    return found


def write_regions(
    header: list[str], title: str, regions: list[Region], sector_comment: str = ""
) -> str:
    """The config text. Each line of `header` becomes a comment line. `sector_comment` follows
    the line that turns off the sector tick marks."""
    stop = max(region.bucket.memory.end for region in regions if region.bucket.memory)
    bits = 64 if stop >= 1 << 32 else BITS
    lines = [*(f"# {comment_safe(line)}" for line in header), "version: 1", "", "figure:"]
    lines += [f"  title: {quote(title)}", "", "memory:"]
    if bits == 64:
        lines.append("  address_bits: 64")
    lines.append("  regions:")
    columns: list[str] = []
    expand: list[str] = []
    for region in regions:
        memory = region.bucket.memory
        assert memory is not None
        lines += [
            f"    - id: {quote(memory.id)}",
            f"      name: {quote(memory.name)}",
        ]
        if region.space is not None:
            comment = f"  # {region.space_reason}" if region.space_reason else ""
            lines.append(f"      space: {quote(region.space)}{comment}")
        lines += [
            f"      start: {address_literal(memory.start, bits)}",
            f"      size: {size_literal(memory.size)}",
        ]
        if region.sector is not None:
            count = memory.size // region.sector
            size = size_literal(region.sector)
            lines.append(f"      sectors: {{ size: {size}, count: {count} }}  # checks alignment (W100)")
        lines.append("      children:")
        for item in region.bucket.items:
            lines += item_lines(item, bits, "        ")
        columns.append(
            f"    - {{ id: {quote(memory.id + '_col')}, root: {quote(memory.id)}, "
            f"title: {quote(usage_title(region.bucket))}, width: {COLUMN_WIDTH} }}"
        )
        for item, within in _expansions(region.bucket.items, memory.name):
            root, column = quote(item.id), quote(f"{item.id}_col")
            name = item.name.replace("\n", " ")
            columns.append(f"    - {{ id: {column}, root: {root}, width: {COLUMN_WIDTH} }}")
            expand.append(f"    - {{ region: {root}, to: {column}, title: {quote(f'{name} in {within}')} }}")
    lines += ["", "view:", "  defaults:", "    labels: { size: true }", "  columns:", *columns]
    if expand:
        lines += ["  expand:", *expand]
    lines += ["", "style:", "  reserved: { show_label: true }  # names the Free blocks"]
    if any(region.sector is not None for region in regions):
        lines.append(f"  sector_ticks: false{sector_comment}")
    lines.append("")
    return "\n".join(lines)


def write_yaml(source: str, kind: str, bucket: Bucket, origins: list[str]) -> str:
    """The config text of an ESP-IDF table: one flash region with 4K sectors. `kind` says what
    `source` is, and each of `origins` becomes a comment line in the header."""
    memory = bucket.memory
    assert memory is not None
    header = [
        f"Generated by `memmap from-partitions` from {source}, {kind}.",
        "Offsets are positions in the flash chip, not CPU addresses. Rename, merge or annotate",
        "blocks freely.",
        *origins,
    ]
    sector = SECTOR if memory.size % SECTOR == 0 else None
    return write_regions(
        header,
        f"{source} flash layout",
        [Region(bucket, sector)],
        "             # 4K sectors are too many to mark",
    )
