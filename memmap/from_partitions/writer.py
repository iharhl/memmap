"""Write a partition table import as config text: one flash region, one line per partition."""

from __future__ import annotations

from ..from_elf.blocks import Bucket
from ..from_elf.sizes import address_literal, size_literal
from ..from_elf.writer import COLUMN_WIDTH, comment_safe, item_lines, quote, usage_title
from .esp_idf import SECTOR

BITS = 32  # flash offsets are drawn with 32-bit addresses


def write_yaml(source: str, kind: str, bucket: Bucket, origins: list[str]) -> str:
    """The config text. `kind` says what `source` is, and each of `origins` becomes a comment
    line in the header."""
    memory = bucket.memory
    assert memory is not None
    lines = [
        f"# Generated by `memmap from-partitions` from {comment_safe(source)}, {kind}.",
        "# Offsets are positions in the flash chip, not CPU addresses. Rename, merge or annotate",
        "# blocks freely.",
        *(f"# {comment_safe(origin)}" for origin in origins),
        "version: 1",
        "",
        "figure:",
        f"  title: {quote(f'{source} flash layout')}",
        "",
        "memory:",
        "  regions:",
        f"    - id: {quote(memory.id)}",
        f"      name: {quote(memory.name)}",
        f"      start: {address_literal(memory.start, BITS)}",
        f"      size: {size_literal(memory.size)}",
    ]
    if memory.size % SECTOR == 0:
        count = memory.size // SECTOR
        lines.append(
            f"      sectors: {{ size: {size_literal(SECTOR)}, count: {count} }}  # checks alignment (W100)"
        )
    lines.append("      children:")
    for item in bucket.items:
        lines += item_lines(item, BITS, "        ")
    title = quote(usage_title(bucket))
    lines += [
        "",
        "view:",
        "  defaults:",
        "    labels: { size: true }",
        "  columns:",
        (
            f"    - {{ id: \"flash_col\", root: {quote(memory.id)}, title: {title}, "
            f"width: {COLUMN_WIDTH} }}"
        ),
        "",
        "style:",
        "  reserved: { show_label: true }  # names the Free blocks",
        "  sector_ticks: false             # 4K sectors are too many to mark",
        "",
    ]
    return "\n".join(lines)
